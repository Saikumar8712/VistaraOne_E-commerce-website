export const generateYouthFashion = (categoryId) => {
  return youthFashionTemplates.map((item, index) => {
    const num = String(index + 1).padStart(3, '0')
    const imgIndex = index % imgs.length
    const imageList = [
      imgs[imgIndex],
      imgs[(imgIndex + 1) % imgs.length],
      imgs[(imgIndex + 2) % imgs.length],
    ]

    const desc = `${item.name}. Features premium ${item.fabric} with ${item.fit}. Designed specifically for ${item.gender} fashion. Available in full youth sizing: S, M, L, XL, XXL. Breathable, durable, and stylish for daily wear, parties, and celebrations.`

    return {
      name: item.name,
      slug: `${item.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')}-${num}`,
      sku: `YTH-${item.gender === 'Boys' ? 'BOY' : 'GRL'}-${num}`,
      category: categoryId,
      brand: item.brand,
      price: item.price,
      originalPrice: item.mrp,
      discountPercent: Math.round(((item.mrp - item.price) / item.mrp) * 100),
      rating: +(4.2 + (index % 7) * 0.1).toFixed(1),
      reviewCount: 45 + (index * 13) % 400,
      stock: 25 + (index % 40),
      description: desc,
      images: imageList,
      highlights: [
        `Sizes Available: S, M, L, XL, XXL`,
        `Target: ${item.gender} Fashion`,
        `Fabric: ${item.fabric}`,
        `Style: ${item.type} (${item.fit})`,
        `Occasion: ${item.occ}`,
      ],
      specifications: [
        { group: 'General', name: 'Brand', value: item.brand },
        { group: 'General', name: 'Target Audience', value: `${item.gender} Fashion` },
        { group: 'General', name: 'Garment Style', value: item.type },
        { group: 'Sizing', name: 'Sizes Available', value: 'S, M, L, XL, XXL' },
        { group: 'Fabric & Fit', name: 'Fabric Composition', value: item.fabric },
        { group: 'Fabric & Fit', name: 'Fit Type', value: item.fit },
        { group: 'Style & Occasion', name: 'Occasion', value: item.occ },
        { group: 'Care & Maintenance', name: 'Care Instructions', value: 'Gentle Machine Wash in Cold Water' },
      ],
      tags: [
        'fashion',
        'clothes',
        'clothing',
        'youth',
        'boys',
        'girls',
        item.gender.toLowerCase(),
        item.type.toLowerCase(),
        'size-s',
        'size-m',
        'size-l',
        'size-xl',
        'size-xxl',
      ],
      isFeatured: !!item.featured,
      isBestseller: !!item.best,
      isDemo: true,
      isActive: true,
    }
  })
}
