export const generateBabyBoys = (categoryId) => {
  return babyBoysTemplates.map((item, index) => {
    const num = String(index + 1).padStart(3, '0')
    const imgIndex = index % imgs.length
    const imageList = [
      imgs[imgIndex],
      imgs[(imgIndex + 1) % imgs.length],
      imgs[(imgIndex + 2) % imgs.length],
    ]

    const desc = `${item.name}. Designed exclusively for baby boys. Crafted from ultra-gentle, skin-friendly ${item.fabric}. Features nickel-free non-scratch snap buttons and gentle elastic bands for tender baby skin. Available in sizes: ${item.sizes}. Perfect for ${item.occ}.`

    return {
      name: item.name,
      slug: `${item.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')}-${num}`,
      sku: `BBY-BOY-${num}`,
      category: categoryId,
      brand: item.brand,
      price: item.price,
      originalPrice: item.mrp,
      discountPercent: Math.round(((item.mrp - item.price) / item.mrp) * 100),
      rating: +(4.4 + (index % 6) * 0.1).toFixed(1),
      reviewCount: 60 + (index * 17) % 350,
      stock: 30 + (index % 35),
      description: desc,
      images: imageList,
      highlights: [
        `Designed Exclusively for Baby Boys`,
        `Available Sizes: ${item.sizes}`,
        `100% Baby-Safe Hypoallergenic Fabric`,
        `Nickel-Free Non-Scratch Snaps`,
        `Occasion: ${item.occ}`,
      ],
      specifications: [
        { group: 'General', name: 'Brand', value: item.brand },
        { group: 'General', name: 'Target Gender', value: 'Baby Boy' },
        { group: 'General', name: 'Product Type', value: item.type },
        { group: 'Sizing', name: 'Available Sizes', value: item.sizes },
        { group: 'Fabric & Care', name: 'Fabric Material', value: item.fabric },
        { group: 'Fabric & Care', name: 'Safety Certification', value: '100% Skin-Safe, Nickel-Free Snaps' },
        { group: 'Usage', name: 'Occasion', value: item.occ },
        { group: 'Care & Maintenance', name: 'Wash Care', value: 'Gentle Baby Detergent Machine Wash' },
      ],
      tags: [
        'baby',
        'baby boy',
        'baby boys',
        'boy baby',
        'infant boy',
        'toddler boy',
        'kids',
        'fashion',
        'clothes',
        'clothing',
        item.type.toLowerCase(),
      ],
      isFeatured: !!item.featured,
      isBestseller: !!item.best,
      isDemo: true,
      isActive: true,
    }
  })
}
